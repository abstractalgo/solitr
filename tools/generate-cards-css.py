#!/usr/bin/env python3
"""Writes decompiled/css/cards.css (one rule per card face, 1x/2x via image-set)."""
import os

out = os.path.join(os.path.dirname(__file__), "..", "decompiled", "css", "cards.css")
lines = ["""/* Card faces. Class names are built in CardController.appendTo():
   "card" + rank letter + suit letter, lowercased (e.g. .cardah = ace of hearts,
   .cardtc = ten of clubs). .cardback is toggled on face-down cards and comes
   last so it overrides the face. images/1x = 79x123, images/2x = 158x246 (retina).
   Generated by tools/generate-cards-css.py. */
"""]

def rule(selector, name):
    one, two = f"url(../images/1x/{name}.png)", f"url(../images/2x/{name}.png)"
    lines.append(f"{selector} {{\n  background-image: {one};\n"
                 f"  background-image: -webkit-image-set({one} 1x, {two} 2x);\n"
                 f"  background-image: image-set({one} 1x, {two} 2x);\n}}")

for suit in "cdhs":
    for rank in "a23456789tjqk":
        rule(f".card{rank}{suit}", rank + suit)
rule(".turnOverWasteImage", "turn-over-waste")
rule(".cardback", "back")

with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(out))
