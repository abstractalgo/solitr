#!/usr/bin/env python3
"""Writes decompiled/css/cards-1x.css and cards-2x.css from decompiled/images/{1x,2x}/*.png.

The images are embedded as base64 data URIs (as on the original site), so every
card face arrives with the stylesheet itself. With separate image files the
browser only fetches a face the first time that card is turned up, and the card
flashes blank until it arrives.

Edit the PNGs, then re-run this script.
"""
import base64, os

root = os.path.join(os.path.dirname(__file__), "..", "decompiled")

HEADER = """/* Card faces at {scale} ({size}). GENERATED by tools/generate-cards-css.py from
   images/{scale}/*.png – edit the images and re-run the script, don't edit this file.
   Class names are built in CardController.appendTo(): "card" + rank letter + suit
   letter, lowercased (e.g. .cardah = ace of hearts, .cardtc = ten of clubs).
   .cardback is toggled on face-down cards and comes last so it overrides the face.
   index.html loads the 1x or 2x file depending on the screen's pixel density. */
"""

rules = [(f".card{rank}{suit}", rank + suit) for suit in "cdhs" for rank in "a23456789tjqk"]
rules += [(".turnOverWasteImage", "turn-over-waste"), (".cardback", "back")]

for scale, size in (("1x", "79x123"), ("2x", "158x246")):
    lines = [HEADER.format(scale=scale, size=size)]
    for selector, name in rules:
        with open(os.path.join(root, "images", scale, name + ".png"), "rb") as f:
            data = base64.b64encode(f.read()).decode()
        lines.append(f"{selector} {{\n  background-image: url(data:image/png;base64,{data});\n}}")
    out = os.path.join(root, "css", f"cards-{scale}.css")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(out), os.path.getsize(out), "bytes")
